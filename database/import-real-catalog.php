<?php
/**
 * Replaces the product catalogue with database/catalog-real.json
 * (real products + photos in uploads/products/real/).
 *
 *   php database/import-real-catalog.php          (wipe + import)
 *   php database/import-real-catalog.php --sql    (also write database/catalog-seed.sql)
 *
 * Past orders keep their item names/prices (order_items.product_id → NULL).
 */
if (PHP_SAPI !== 'cli') exit('CLI only');
require dirname(__DIR__) . '/config.php';

$items = json_decode(file_get_contents(__DIR__ . '/catalog-real.json'), true);
if (!$items) exit("catalog-real.json missing or invalid\n");

$pdo = db();
$pdo->exec('SET FOREIGN_KEY_CHECKS=0');
$pdo->exec('DELETE FROM cart_items');
$pdo->exec('UPDATE order_items SET product_id = NULL');
$pdo->exec('UPDATE prescription_items SET product_id = NULL');
$pdo->exec('DELETE FROM products');
$pdo->exec('DELETE FROM categories');
$pdo->exec('ALTER TABLE products AUTO_INCREMENT = 1');
$pdo->exec('ALTER TABLE categories AUTO_INCREMENT = 1');
$pdo->exec('SET FOREIGN_KEY_CHECKS=1');

$catIds = []; $counts = []; $sqlCats = []; $sqlProducts = [];
$byCat = [];
foreach ($items as $p) $byCat[$p['category']][] = $p;
ksort($byCat);
foreach ($byCat as $cat => $list) {
    q('INSERT INTO categories (name, icon) VALUES (?, ?)', [$cat, $list[0]['icon']]);
    $catId = (int)$pdo->lastInsertId();
    $sqlCats[] = sprintf('(%s, %s)', $pdo->quote($cat), $pdo->quote($list[0]['icon']));
    foreach ($list as $p) {
        if (!is_file(ROOT_PATH . '/' . $p['image'])) continue;
        $h = abs(crc32($p['name']));
        $stock = $p['rx'] ? 20 + $h % 41 : 15 + $h % 136;
        $rating = number_format(3.8 + ($h % 13) / 10, 2);
        $desc = $p['description'] . ($p['rx'] ? ' PRESCRIPTION REQUIRED — upload a valid prescription at checkout.' : '');
        q('INSERT INTO products (category_id, name, description, price, stock, image_path, rating, requires_prescription, is_active)
           VALUES (?,?,?,?,?,?,?,?,1)', [$catId, $p['name'], $desc, $p['price'], $stock, $p['image'], $rating, $p['rx']]);
        $sqlProducts[] = sprintf('((SELECT id FROM categories WHERE name=%s), %s, %s, %.2f, %d, %s, %s, %d)',
            $pdo->quote($cat), $pdo->quote($p['name']), $pdo->quote($desc), $p['price'], $stock, $pdo->quote($p['image']), $rating, $p['rx']);
        $counts[$cat] = ($counts[$cat] ?? 0) + 1;
    }
}
foreach ($counts as $c => $n) printf("%-26s %3d\n", $c, $n);
echo 'TOTAL: ' . array_sum($counts) . ' products, ' . count($counts) . " categories\n";

if (in_array('--sql', $argv, true)) {
    file_put_contents(__DIR__ . '/catalog-seed.sql', "INSERT INTO categories (name, icon) VALUES\n" . implode(",\n", $sqlCats) . ";\n\n"
        . "-- Product catalogue (generated by database/import-real-catalog.php)\n"
        . "INSERT INTO products (category_id, name, description, price, stock, image_path, rating, requires_prescription) VALUES\n"
        . implode(",\n", $sqlProducts) . ";\n");
    echo "Wrote database/catalog-seed.sql\n";
}
